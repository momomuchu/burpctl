package com.burprest.services

import burp.api.montoya.MontoyaApi
import burp.api.montoya.collaborator.CollaboratorClient
import burp.api.montoya.collaborator.InteractionFilter
import burp.api.montoya.collaborator.InteractionType
import com.burprest.models.BatchGenerateResponse
import com.burprest.models.CollaboratorPayload
import com.burprest.models.GeneratePayloadResponse
import com.burprest.models.Interaction
import com.burprest.models.PollResponse
import java.util.Base64
import java.util.concurrent.ConcurrentHashMap

/** The Collaborator capability or its client could not be initialized. */
class CollaboratorUnavailableException(
    message: String = "Burp Collaborator is unavailable.",
    cause: Throwable? = null,
) : RuntimeException(message, cause)

/** An initialized Collaborator provider failed while generating or polling. */
class CollaboratorProviderException(
    message: String = "The Burp Collaborator provider failed.",
    cause: Throwable? = null,
) : RuntimeException(message, cause)

/** The requested payload was not generated by this in-memory service instance. */
class CollaboratorPayloadNotFoundException(id: String) :
    RuntimeException("Collaborator payload not found: $id")

class CollaboratorService(private val api: MontoyaApi) {

    private var client: CollaboratorClient? = null
    private val payloads = ConcurrentHashMap<String, burp.api.montoya.collaborator.CollaboratorPayload>()

    @Synchronized
    private fun ensureClient(): CollaboratorClient {
        client?.let { return it }

        val collaborator = try {
            api.collaborator()
        } catch (exception: Exception) {
            throw CollaboratorUnavailableException(cause = exception)
        } ?: throw CollaboratorUnavailableException()

        val createdClient = try {
            collaborator.createClient()
        } catch (exception: Exception) {
            throw CollaboratorUnavailableException(cause = exception)
        } ?: throw CollaboratorUnavailableException()

        client = createdClient
        return createdClient
    }

    fun generatePayload(): GeneratePayloadResponse {
        val collaboratorClient = ensureClient()
        return try {
            val generated = collaboratorClient.generatePayload()
                ?: throw CollaboratorProviderException()
            val correlationId = generated.id().toString()
            val payloadValue = generated.toString()

            payloads[correlationId] = generated
            GeneratePayloadResponse(
                payload = CollaboratorPayload(
                    id = correlationId,
                    payload = payloadValue,
                    interactionId = correlationId,
                ),
            )
        } catch (exception: CollaboratorProviderException) {
            throw exception
        } catch (exception: Exception) {
            throw CollaboratorProviderException(cause = exception)
        }
    }

    fun generateBatch(count: Int): BatchGenerateResponse {
        require(count in 1..MAX_BATCH_SIZE) {
            "count must be between 1 and $MAX_BATCH_SIZE, got $count"
        }
        return BatchGenerateResponse(
            payloads = List(count) { generatePayload().payload },
        )
    }

    fun poll(): PollResponse {
        val collaboratorClient = ensureClient()
        return try {
            val interactions = collaboratorClient.getAllInteractions().map { it.toModel() }
            PollResponse(
                found = interactions.isNotEmpty(),
                interactions = interactions,
            )
        } catch (exception: Exception) {
            throw CollaboratorProviderException(cause = exception)
        }
    }

    fun pollById(id: String): PollResponse {
        if (!payloads.containsKey(id)) {
            throw CollaboratorPayloadNotFoundException(id)
        }

        val collaboratorClient = ensureClient()
        return try {
            val filter = InteractionFilter.interactionIdFilter(id)
            val interactions = collaboratorClient.getInteractions(filter).map { it.toModel() }
            PollResponse(
                found = interactions.isNotEmpty(),
                interactions = interactions,
                queriedPayloadId = id,
            )
        } catch (exception: Exception) {
            throw CollaboratorProviderException(cause = exception)
        }
    }

    private fun burp.api.montoya.collaborator.Interaction.toModel(): Interaction {
        val interactionType = type()
        return Interaction(
            id = id().toString(),
            type = interactionType.name,
            clientIp = clientIp().hostAddress,
            clientPort = clientPort(),
            timestamp = timeStamp().toString(),
            details = details(interactionType),
        )
    }

    private fun burp.api.montoya.collaborator.Interaction.details(
        interactionType: InteractionType,
    ): Map<String, String> = when (interactionType) {
        InteractionType.DNS -> dnsDetails().orElse(null)?.let { dns ->
            mapOf(
                "queryType" to dns.queryType().name,
                "query" to dns.query().getBytes().toBase64(),
            )
        } ?: emptyMap()

        InteractionType.HTTP -> httpDetails().orElse(null)?.let { http ->
            val requestResponse = http.requestResponse()
            buildMap {
                put("protocol", http.protocol().name)
                put("request", requestResponse.request().toByteArray().getBytes().toBase64())
                if (requestResponse.hasResponse()) {
                    put("response", requestResponse.response().toByteArray().getBytes().toBase64())
                }
            }
        } ?: emptyMap()

        InteractionType.SMTP -> smtpDetails().orElse(null)?.let { smtp ->
            mapOf(
                "protocol" to smtp.protocol().name,
                "conversation" to smtp.conversation(),
            )
        } ?: emptyMap()

        else -> emptyMap()
    }

    private fun kotlin.ByteArray.toBase64(): String = Base64.getEncoder().encodeToString(this)

    private companion object {
        const val MAX_BATCH_SIZE = 100
    }
}
